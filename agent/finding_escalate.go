package agent

import "context"

// EscalationResult 是一次「扩大危害」的写回请求。TaskID 由 ToolSet 填(用于校验
// 该漏洞确实属于本任务),server 侧据此拒绝跨任务改写。
type EscalationResult struct {
	TaskID    int64
	FindingID int64
	Success   bool
	Severity  string
	Evidence  string
	Summary   string
}

// EscalationWriter 写回一次升级结果。由 server 侧实现并接线到 Worker。
type EscalationWriter func(ctx context.Context, r EscalationResult) error

// ---------------------------------------------------------------------------
// 危害升级手册(移植 StanleyNull/AutoHunter 的「扩大危害 Hunter」ESCALATE 提示词)。
//
// 用在「已采纳的低危/中危漏洞」自动派出的那条升级意图上:worker 领到的不是"找新洞",
// 而是"顺着已经打开的口子再往下打一层,把评级顶上去"。
//
// 与 worker 常规提示词的分工:常规提示词管"怎么挖、别报垃圾",本手册管"拿到一个
// 已确认的据点后,按它属于哪一类,照着对应打法把危害做大"。
